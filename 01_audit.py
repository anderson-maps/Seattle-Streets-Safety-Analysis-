"""Phase 1 data audit. Reads raw SDOT collisions + Seattle streets files and writes
docs/data_audit.md and data/processed/collisions_clean.csv.gz. Every number in the audit
is computed here; nothing is typed by hand."""
import numpy as np
import pandas as pd
from config import COLLISIONS_CSV, STREETS_CSV, PROCESSED, DOCS, KSI_CODES

df = pd.read_csv(COLLISIONS_CSV, low_memory=False)
st = pd.read_csv(STREETS_CSV, low_memory=False)

# SDOT's INCDATE carries a placeholder 8:00 AM time; INCDTTM holds the actual time.
df["dt"] = pd.to_datetime(df["INCDTTM"], format="mixed")
df["year"] = df.dt.dt.year
df["hour"] = df.dt.dt.hour
df["ksi"] = df.SEVERITYCODE.isin(KSI_CODES)
df["ksi_any_flag"] = (
    df.ksi | (df.SERIOUSINJURY == "Y") | (df.FATALITY == "Y")
    | (df.SERIOUSINJURIES > 0) | (df.FATALITIES > 0)
)
df["mode"] = np.select([df.PEDCOUNT > 0, df.PEDCYLCOUNT > 0], ["pedestrian", "bicyclist"], "motor_only")
df["has_coords"] = df.x.notna() & df.y.notna()

k = df[df.ksi]
L = []
def h(t): L.extend(["", f"## {t}", ""])
def p(t): L.append(t)

p("# Data audit")
p("")
p("Generated by `src/01_audit.py` from the raw files. Do not edit by hand.")
h("Collisions file")
p(f"- Records: {len(df):,}; date range {df.dt.min():%Y-%m-%d} to {df.dt.max():%Y-%m-%d}")
p(f"- Missing coordinates: {(~df.has_coords).sum():,} ({(~df.has_coords).mean():.1%}); among KSI: {(~k.has_coords).sum():,} ({(~k.has_coords).mean():.1%})")
p(f"- Duplicate OBJECTID / INCKEY / COLDETKEY: {df.OBJECTID.duplicated().sum()} / {df.INCKEY.duplicated().sum()} / {df.COLDETKEY.duplicated().sum()}; repeated REPORTNO: {df.REPORTNO.duplicated().sum()}")
p(f"- Source: {df['Source description'].value_counts().to_dict()}")
h("KSI definition and severity-coding consistency")
p(f"- KSI (SEVERITYCODE in {KSI_CODES}): {len(k):,}; union of all serious/fatal flags: {df.ksi_any_flag.sum():,}")
p(f"- Fatal collisions: SEVERITYCODE=4 {(df.SEVERITYCODE==4).sum()}, FATALITY=Y {(df.FATALITY=='Y').sum()}, FATALITIES>0 {(df.FATALITIES>0).sum()}")
gap = df[df.SEVERITYCODE == 4].groupby("year").agg(code4=("OBJECTID", "size"), people_killed_recorded=("FATALITIES", lambda s: int((s > 0).sum())))
p("- Fatal-coded collisions where FATALITIES field is populated, by year:")
p("")
p(gap.T.to_markdown())
h("KSI by year")
t = pd.DataFrame({"all_collisions": df.groupby("year").size(), "KSI": k.groupby("year").size()}).fillna(0).astype(int)
t["KSI_share_pct"] = (t.KSI / t.all_collisions * 100).round(1)
p(t.to_markdown())
h("KSI by mode")
p(k["mode"].value_counts().to_markdown())
h("Join to street file (no geometry needed)")
st_int = pd.concat([st[["INTKEYLO"]].set_axis(["k"], axis=1), st[["INTKEYHI"]].set_axis(["k"], axis=1)]).k.drop_duplicates()
blk, inter = k[k.ADDRTYPE == "B"], k[k.ADDRTYPE == "I"]
p(f"- Block-level KSI matching a street COMPKEY via ADDR_SEGINTKEY: {blk.ADDR_SEGINTKEY.isin(st.COMPKEY).mean():.1%} (n={len(blk):,})")
p(f"- Intersection-level KSI matching an intersection key: {inter.ADDR_SEGINTKEY.isin(st_int).mean():.1%} (n={len(inter):,})")
p(f"- Street segments: {len(st):,}; intersections derivable: {len(st_int):,}")
h("Known limitations")
for s in [
    "Street file has midpoint coordinates only (no line geometry), no lane counts, volumes, signals, crosswalks, bike facilities, lighting, High Injury Network or equity index.",
    "FATALITIES (people killed) is unreliable in 2004-2005 and 2011; fatal collisions are counted from SEVERITYCODE instead.",
    "Total reported collisions fall sharply from 2020; KSI share of collisions is not a valid risk measure.",
    "UNDERINFL mixes N/Y and 0/1 codes; SPEEDING is Y or blank.",
    "No exposure data is included yet.",
]:
    p(f"- {s}")

DOCS.mkdir(exist_ok=True); PROCESSED.mkdir(parents=True, exist_ok=True)
(DOCS / "data_audit.md").write_text("\n".join(L) + "\n")
df.drop(columns=["SE_ANNO_CAD_DATA"]).to_csv(PROCESSED / "collisions_clean.csv.gz", index=False)
print("wrote docs/data_audit.md")
